"""Throughput and per-stage latency of the live pipeline, on GPU and CPU.

    cd perception-service
    python -m evaluation.benchmark                    # demo_videos/, 90 s per device
    python -m evaluation.benchmark --seconds 120 --devices gpu

Runs main.py on the demo playlist exactly as in live use (paced at
detection_fps, so detector gates and strides behave normally), with timing on
(--stats-json). CPU runs hide the GPU with CUDA_VISIBLE_DEVICES=-1.

Reported per stage: mean ms per processed frame. Detectors are called on every
frame but run their model only on a stride or when their gate opens, so this is
the average cost they add to a frame, not the time of one model inference.
"Capacity" = 1000 / mean ms per processed frame, i.e. the frame rate the
pipeline could sustain if it were not paced at detection_fps.
Writes the "benchmark" section of docs/RESULTS.md and docs/results/benchmark.json.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from evaluation.common import RESULTS_DIR, SERVICE_ROOT, update_section

QUIET_ENV = {"DASHBOARD_BACKEND_URL": "", "DASHBOARD_API_TOKEN": "", "DASHBOARD_SERVICE_EMAIL": "",
             "LLM_API_KEY": "", "LEGACY_INCIDENT_API_URL": ""}
STAGES = [("yolo_detect", "YOLOv8n person/object detection"), ("bytetrack", "ByteTrack tracking"),
          ("rule_engine", "Rule engine (loitering, intrusion, crowd)"), ("fight", "Fight (R3D-18 + interaction)"),
          ("fire_smoke", "Fire/smoke (YOLOv8n + verifier)"), ("fall", "Fall (YOLOv8-Pose + BiGRU)"),
          ("anomaly", "Unusual activity (optical flow + autoencoder)"), ("cycle_total", "Whole frame")]


def run_device(device: str, demo: str, seconds: float, work: Path) -> dict:
    stats = work / f"{device}.json"
    env = {**os.environ, **QUIET_ENV}
    if device == "cpu":
        env["CUDA_VISIBLE_DEVICES"] = "-1"
    cmd = [sys.executable, "main.py", "--demo", demo, "--no-display", "--max-seconds", str(seconds),
           "--output-dir", str(work / device), "--stats-json", str(stats)]
    for attempt in (1, 2):
        print(f"[{device}] run {attempt}: {' '.join(cmd)}")
        result = subprocess.run(cmd, cwd=SERVICE_ROOT, env=env, capture_output=True, text=True,
                                encoding="utf-8", errors="replace")
        if result.returncode == 0 and stats.exists():
            data = json.loads(stats.read_text(encoding="utf-8"))
            data["attempts"] = attempt
            return data
        print(f"[{device}] exited with {result.returncode}; output tail:\n{result.stdout[-1500:]}")
    raise SystemExit(f"{device} benchmark failed twice")


def hardware() -> dict:
    info = {"os": platform.platform(), "cpu": platform.processor() or platform.machine(),
            "python": platform.python_version()}
    try:
        import torch
        info["torch"] = torch.__version__
        if torch.cuda.is_available() and torch.cuda.device_count():
            info["gpu"] = torch.cuda.get_device_name(0)
    except ImportError:
        pass
    return info


def markdown(result: dict) -> str:
    runs = result["runs"]
    hw = result["hardware"]
    out = ["## 3. Speed: frames per second and per-stage latency", "",
           f"Generated by `python -m evaluation.benchmark` on {result['run_at'][:10]}: "
           f"{result['seconds']:.0f} s of the demo playlist per device, paced at "
           f"{result['detection_fps']} processed frames/s as in live use, 640×480 processing resolution.", "",
           f"Hardware: {hw.get('cpu')}; GPU: {hw.get('gpu', 'none')}; {hw.get('os')}; "
           f"Python {hw.get('python')}, PyTorch {hw.get('torch', '?')}.", ""]
    head = "| Stage | " + " | ".join(f"{d.upper()} ms per frame" for d in runs) + " |"
    out += [head, "|---|" + "---|" * len(runs)]
    for key, label in STAGES:
        cells = []
        for d in runs:
            s = runs[d]["stages"].get(key)
            cells.append(f"{s['mean_ms_per_cycle']:.1f}" if s else "–")
        out.append(f"| {label} | " + " | ".join(cells) + " |")
    out += ["", "| | " + " | ".join(d.upper() for d in runs) + " |", "|---|" + "---|" * len(runs)]
    out.append("| Processed frames/s achieved (target "
               f"{result['detection_fps']}) | " + " | ".join(f"{runs[d]['cycles_per_s']:.1f}" for d in runs) + " |")
    out.append("| Capacity, frames/s (1000 / ms per frame) | "
               + " | ".join(f"{runs[d]['pipeline_capacity_fps']:.1f}" for d in runs) + " |")
    out += ["", "ms per frame = average time the stage adds to each processed frame. The fight, "
                "fire/smoke, fall and unusual-activity detectors run their model only on a stride or when "
                "their gate opens, so one inference takes longer than the average shown. \"Whole frame\" "
                "also includes resizing and evidence buffering; video decoding is not included. Timings "
                "depend on what is in view (the fight and fall models only run when people are present)."]
    if any(r.get("attempts", 1) > 1 for r in runs.values()):
        out += ["", "Note: a run crashed natively and was repeated (seen intermittently with CPU-only "
                    "PyTorch on Windows)."]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--demo", default="demo_videos")
    parser.add_argument("--seconds", type=float, default=90)
    parser.add_argument("--devices", nargs="+", choices=["gpu", "cpu"], default=["gpu", "cpu"])
    parser.add_argument("--no-write", action="store_true")
    parser.add_argument("--render-only", action="store_true",
                        help="rewrite the RESULTS.md section from docs/results/benchmark.json")
    args = parser.parse_args()
    if args.render_only:
        update_section("benchmark", markdown(json.loads((RESULTS_DIR / "benchmark.json").read_text("utf-8"))))
        return

    import yaml
    fps = yaml.safe_load((SERVICE_ROOT / "config/thresholds.yaml").read_text())["perception"]["detection_fps"]
    hw = hardware()
    devices = [d for d in args.devices if d == "cpu" or "gpu" in hw]
    if "gpu" in args.devices and "gpu" not in hw:
        print("no CUDA GPU available -- GPU benchmark skipped")
    with tempfile.TemporaryDirectory(prefix="benchmark_") as tmp:
        runs = {d: run_device(d, args.demo, args.seconds, Path(tmp)) for d in devices}
    result = {"run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "seconds": args.seconds,
              "detection_fps": fps, "hardware": hw, "runs": runs}
    text = markdown(result)
    print(text)
    if not args.no_write:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        (RESULTS_DIR / "benchmark.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
        update_section("benchmark", text)
        print("written to docs/RESULTS.md and docs/results/benchmark.json")


if __name__ == "__main__":
    main()
